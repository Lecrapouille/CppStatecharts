#include "Statechart/Event.hpp"

#include <utility>

namespace statechart {

Event::Event(std::string p_id) : m_id(std::move(p_id)) {}

bool Event::equals(const Event* p_event,
                   Metadata& /*p_data*/,
                   Parameter& /*p_param*/) const
{
    if (p_event == nullptr)
    {
        return false;
    }
    return m_id == p_event->m_id;
}

} // namespace statechart
